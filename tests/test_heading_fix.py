"""Section labels seen in the REAL Step B prompts that were table cells or list items, not headings."""
import pytest

from app.chunking import is_heading, paper_words


@pytest.mark.parametrize("line", [
    "1.05 Bits-per-byte", "0.84 Bits-per-byte", "2.95 Perplexity on HG38", "49.7 Moshi after multi-stream instruct, synthetic voice",
    "23.75 Deep-Att + PosUnk [39]", "51.6 H-Net (space)", "52.0 Mistral", "93.0 Dyer et al. (2016) [8]",
    "1. Deduplication of source content. Removing frequent duplicates to avoid overfitting",
])
def test_real_table_cells_and_list_items_are_not_headings(line):
    assert not is_heading(line)


@pytest.mark.parametrize("line", [
    "1 Introduction", "3.2 Attention", "3.2.1 Scaled Dot-Product Attention", "5.5 Spoken question answering",
    "2.4 Autoregressive Training and Inference", "10 Conclusion", "6.4 Identification of the content generated by Moshi: Watermarking",
    "Abstract", "References",
])
def test_real_headings_are_still_headings(line):
    assert is_heading(line)


def test_a_table_cell_does_not_replace_the_current_section():
    words = paper_words([(1, "3.2 Attention\nSome text here\n1.05 Bits-per-byte\nmore text")])
    assert {w.section for w in words} == {"3.2 Attention"}


def test_headings_that_go_backwards_or_far_ahead_are_ignored():
    # real wrong labels seen in the Moshi and H-Net audits: "1 Text delay", "20.2 LlamaByte (W1024)"
    page = ("1 Introduction\naaa\n2 Background\nbbb\n3 Model\nccc\n1 Text delay\nddd\n"
            "20.2 LlamaByte (W1024)\neee\n3.1 Encoder Stacks\nfff")
    words = paper_words([(1, page)])
    all_sections = {w.section for w in words}
    assert "1 Text delay" not in all_sections and "20.2 LlamaByte (W1024)" not in all_sections
    section_of = {w.text: w.section for w in words}
    assert section_of["ddd"] == "3 Model" and section_of["eee"] == "3 Model"
    assert section_of["fff"] == "3.1 Encoder Stacks"


def test_a_second_plain_heading_with_the_same_top_number_is_ignored():
    page = "3 Model\nx\n4 Entropy\ny\n4 MosNet +\nz"
    words = paper_words([(1, page)])
    assert [w.section for w in words if w.text == "z"] == ["4 Entropy"]  # known limit: the first "4 ..." wins


def test_chunk_is_labelled_with_the_section_most_of_its_words_belong_to():
    from app.chunking import Word, make_chunks
    from app.config import Paper

    paper = Paper(key="p", title="t", arxiv_id="1.1", version=1)
    words = ([Word("a", 1, "A")] * 2) + ([Word("b", 1, "B")] * 4)
    assert make_chunks(paper, words, 6, 0, "X")[0].section == "B"  # first word is in A, most words are in B
    tie = ([Word("a", 1, "A")] * 3) + ([Word("b", 1, "B")] * 3)
    assert make_chunks(paper, tie, 6, 0, "X")[0].section == "A"  # ties go to the earlier section


def test_a_dotted_heading_that_goes_back_to_an_earlier_section_is_ignored():
    page = "5 Results\nx\n2.1 Table row look-alike\ny\n5.1 Real subsection\nz"
    section_of = {w.text: w.section for w in paper_words([(1, page)])}
    assert section_of["y"] == "5 Results" and section_of["z"] == "5.1 Real subsection"
